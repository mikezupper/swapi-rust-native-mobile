#!/usr/bin/env python3
"""Generate native constants; --check verifies drift and semantic text contrast."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def luminance(value):
    channels = [int(value[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    linear = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels]
    return sum(c * w for c, w in zip(linear, (.2126, .7152, .0722)))


def generate():
    data = json.loads((ROOT / 'design/tokens.json').read_text())
    for palette in data['colors'].values():
        assert all(re.fullmatch('[0-9A-F]{6}', v) for v in palette.values()), 'Invalid RGB color'
    for mode in ('light', 'dark'):
        palette = data['colors'][mode]
        pairs = [(fg, bg) for fg in ('text', 'secondary', 'accent', 'warm') for bg in ('background', 'surface')]
        pairs.append(('onAccent', 'accent'))
        for fg, bg in pairs:
            values = sorted((luminance(palette[fg]), luminance(palette[bg])))
            ratio = (values[1] + .05) / (values[0] + .05)
            if ratio < 4.5:
                raise ValueError(f'{mode}: {fg} on {bg} contrast {ratio:.2f} is below 4.5:1')
    for group in ('space', 'shape', 'typography', 'motion'):
        assert all(isinstance(v, int) and v > 0 for v in data[group].values())
    kotlin = ['// Generated by scripts/generate-design.py. Do not edit.', 'package dev.holocron.app', '', 'import androidx.compose.ui.graphics.Color', '', 'object DesignTokens {']
    swift = ['// Generated by scripts/generate-design.py. Do not edit.', 'import SwiftUI', '', 'enum DesignTokens {']
    for mode, colors in data['colors'].items():
        name = mode.capitalize()
        kotlin.append(f'    object {name} {{')
        swift.append(f'    enum {name} {{')
        for role, color in colors.items():
            kotlin.append(f'        val {role} = Color(0xFF{color})')
            rgb = [int(color[i:i + 2], 16) for i in (0, 2, 4)]
            swift.append(f'        static let {role} = Color(red: {rgb[0]}.0 / 255, green: {rgb[1]}.0 / 255, blue: {rgb[2]}.0 / 255)')
        kotlin.append('    }'); swift.append('    }')
    for group in ('space', 'shape', 'typography', 'motion'):
        name = group.capitalize()
        kotlin.append(f'    object {name} {{'); swift.append(f'    enum {name} {{')
        for role, value in data[group].items():
            kotlin.append(f'        const val {role} = {value}')
            swift.append(f'        static let {role}: CGFloat = {value}')
        kotlin.append('    }'); swift.append('    }')
    kotlin.append('}'); swift.append('}')
    return {
        ROOT / 'android/app/src/main/java/dev/holocron/app/DesignTokens.kt': '\n'.join(kotlin) + '\n',
        ROOT / 'ios/Holocron/DesignTokens.swift': '\n'.join(swift) + '\n',
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, source in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f'Generated token drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(source)
    print('Design tokens match; semantic text colors meet 4.5:1 contrast.' if args.check else 'Generated Kotlin and Swift design tokens.')


if __name__ == '__main__':
    main()
